/**
 * Mendapatkan URL Thumbnail langsung dari CDN resmi YouTube
 * Resolusi:
 * - 'maxresdefault' : 1280x720 (High Definition)
 * - 'hqdefault' : 480x360 (Standard High Quality fallback)
 * - 'mqdefault' : 320x180 (Medium)
 */
export function getYouTubeThumbnail(videoId, quality = 'maxresdefault') {
  return `https://img.youtube.com/vi/${videoId}/${quality}.jpg`;
}

/**
 * URL iFrame Embed resmi YouTube
 */
export function getYouTubeEmbedUrl(videoId, autoplay = 1) {
  return `https://www.youtube.com/embed/${videoId}?autoplay=${autoplay}&rel=0&modestbranding=1`;
}
